-- 平台启动时自动建表（spring.sql.init.mode=always）
-- QL_RULE：规则标准表（与 SDK 共享，供 JdbcRuleLoader / HTTP API 读取）

CREATE TABLE IF NOT EXISTS QL_RULE (
  RULE_ID       VARCHAR(64) PRIMARY KEY,
  RULE_NAME     VARCHAR(128) NOT NULL,
  RULE_CONTENT  CLOB NOT NULL,
  PARAM_DEF     CLOB,
  VERSION       INT DEFAULT 1,
  ENABLED       BOOLEAN DEFAULT TRUE,
  DESCRIPTION   VARCHAR(256),
  CREATED_AT    BIGINT,
  UPDATED_AT    BIGINT
);

CREATE TABLE IF NOT EXISTS QL_RULE_HISTORY (
  ID            BIGINT AUTO_INCREMENT PRIMARY KEY,
  RULE_ID       VARCHAR(64) NOT NULL,
  VERSION       INT NOT NULL,
  RULE_CONTENT  CLOB NOT NULL,
  PARAM_DEF     CLOB,
  SAVED_AT      BIGINT
);
CREATE INDEX IF NOT EXISTS IDX_RULE_VER ON QL_RULE_HISTORY (RULE_ID, VERSION);

-- 启动时从 data/*.json 加载的业务数据镜像（H2 只读副本，主数据仍是 JSON）
CREATE TABLE IF NOT EXISTS QL_SCRIPT (
  ID          VARCHAR(64) PRIMARY KEY,
  NAME        VARCHAR(128),
  RULE_ID     VARCHAR(64),
  SORT_TIME   BIGINT,
  DATA        CLOB
);
CREATE TABLE IF NOT EXISTS QL_EXECUTION (
  ID          VARCHAR(64) PRIMARY KEY,
  SCRIPT_ID   VARCHAR(64),
  SORT_TIME   BIGINT,
  DATA        CLOB
);
CREATE TABLE IF NOT EXISTS QL_COMPARE_RULE (
  ID          VARCHAR(64) PRIMARY KEY,
  NAME        VARCHAR(128),
  RULE_ID     VARCHAR(64),
  SORT_TIME   BIGINT,
  DATA        CLOB
);
CREATE TABLE IF NOT EXISTS QL_COMPARE_RECORD (
  ID          VARCHAR(64) PRIMARY KEY,
  RULE_ID     VARCHAR(64),
  SORT_TIME   BIGINT,
  DATA        CLOB
);
CREATE TABLE IF NOT EXISTS QL_COMPARE_SCHEDULE (
  ID          VARCHAR(64) PRIMARY KEY,
  RULE_ID     VARCHAR(64),
  SORT_TIME   BIGINT,
  DATA        CLOB
);
