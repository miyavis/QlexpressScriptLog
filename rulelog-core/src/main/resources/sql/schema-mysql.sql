-- QLExpress 规则平台标准表结构（MySQL）
-- 平台与 SDK 共享：规则集中存储，SDK 通过 JdbcRuleLoader 读取

CREATE TABLE IF NOT EXISTS QL_RULE (
  RULE_ID       VARCHAR(64) PRIMARY KEY COMMENT '规则逻辑名，如 vip_discount',
  RULE_NAME     VARCHAR(128) NOT NULL COMMENT '显示名',
  RULE_CONTENT  TEXT NOT NULL COMMENT 'QLExpress 脚本文本',
  PARAM_DEF     TEXT COMMENT '参数契约 JSON（ParamDef 数组）',
  VERSION       INT DEFAULT 1 COMMENT '版本号',
  ENABLED       TINYINT(1) DEFAULT 1 COMMENT '是否启用',
  DESCRIPTION   VARCHAR(256) COMMENT '说明',
  CREATED_AT    BIGINT COMMENT '创建时间戳',
  UPDATED_AT    BIGINT COMMENT '更新时间戳'
) COMMENT='规则定义表';

CREATE TABLE IF NOT EXISTS QL_RULE_HISTORY (
  ID            BIGINT PRIMARY KEY AUTO_INCREMENT,
  RULE_ID       VARCHAR(64) NOT NULL,
  VERSION       INT NOT NULL,
  RULE_CONTENT  TEXT NOT NULL,
  PARAM_DEF     TEXT,
  SAVED_AT      BIGINT,
  INDEX IDX_RULE_VER (RULE_ID, VERSION)
) COMMENT='规则版本历史表';
